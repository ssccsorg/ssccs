//! Emission of an observation module from a constraint program.
//!
//! A Scheme's admissible set is a composition of constraint kinds over one coordinate, and the path from that
//! coordinate to a projection through `observe` is fixed. This module writes the SystemVerilog for that pair: the
//! units under `sv/constraints/` with the program's bounds baked in, the declared join of their results, one
//! projector unit, and `observe` around them.
//!
//! The emitted module instantiates the units rather than restating them. A unit is where a kind's semantics live,
//! including the signed comparison that puts a coordinate's i64 order above its unsigned one, so an emitter that
//! inlined comparisons would be a second definition of the same constraint and the two could drift.
//!
//! Bounds are structure here: the emitter fixes them when it writes the module. Keeping a bound as data is the other
//! case, and the board's unit table is it, carrying a kind and its operands so an image answers an inquiry its
//! fabric never saw. The two are different modules rather than two settings of one.

use ssccs_core::ConstraintSpec;

/// How a program joins its constraints.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ComposeOp {
    /// Every constraint admits the coordinate.
    And,
    /// Any constraint admits the coordinate.
    Or,
}

impl ComposeOp {
    fn operator(self) -> &'static str {
        match self {
            ComposeOp::And => "&&",
            ComposeOp::Or => "||",
        }
    }

    fn word(self) -> &'static str {
        match self {
            ComposeOp::And => "and",
            ComposeOp::Or => "or",
        }
    }
}

/// A Scheme's admissible set over one coordinate, as data.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ConstraintProgram {
    /// Constraints over the same coordinate, joined by [`ComposeOp`].
    pub constraints: Vec<ConstraintSpec>,
    /// The join. An empty program is the whole space whatever the join is.
    pub compose: ComposeOp,
}

impl ConstraintProgram {
    /// One line naming the admissible set, for the emitted header.
    pub fn describe(&self) -> String {
        if self.constraints.is_empty() {
            return "no constraints (the whole space)".to_string();
        }
        self.constraints
            .iter()
            .map(describe_spec)
            .collect::<Vec<_>>()
            .join(&format!(" {} ", self.compose.word()))
    }
}

/// The projector units that take one coordinate and return one.
///
/// A unit with more than one input port is absent on purpose: the emitter wires `coord` to `result`, so an instance
/// of a two-input unit would leave a port unconnected and the design would answer something the program never
/// stated. A program needing one of those gets a module written for it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProjectorUnit {
    Identity,
    Parity,
    Negate,
}

impl ProjectorUnit {
    /// The unit's module name under `sv/projectors/`.
    pub fn module_name(self) -> &'static str {
        match self {
            ProjectorUnit::Identity => "proj_identity",
            ProjectorUnit::Parity => "proj_parity",
            ProjectorUnit::Negate => "proj_negate",
        }
    }
}

/// Write the module for `program` and `projector`.
///
/// The module is combinational: the constraints, their join, the projection and `observe` are all gates, and the
/// only state a design needs around it is the one that presents a coordinate. `module` must be an identifier no
/// unit under `sv/` uses, because `make -C sv elaborate` reads both in one pass and a repeated name is ambiguous
/// there rather than here. That gate is the check, which is why this function returns text rather than a Result.
pub fn emit_observation_sv(
    module: &str,
    program: &ConstraintProgram,
    projector: ProjectorUnit,
) -> String {
    let mut sv = String::new();

    sv.push_str(
        "// Generated by ssccs-hardware-mapping. The emitter is the source of this file.\n",
    );
    sv.push_str("//\n");
    sv.push_str(&format!("// Admissible set: {}\n", program.describe()));
    sv.push_str(&format!(
        "// Projection: {}, observed through observe.\n",
        projector.module_name()
    ));
    sv.push_str("//\n");
    if program
        .constraints
        .iter()
        .any(|spec| !matches!(spec, ConstraintSpec::Even))
    {
        sv.push_str("// The bounds are structure: the emitter fixes them here. A substrate that carries a bound as\n");
        sv.push_str(
            "// data reads it from a table instead, and the board's unit table is that case.\n",
        );
    }

    sv.push_str(&format!("module {module} (\n"));
    sv.push_str("    input  logic [63:0] coord,\n");
    sv.push_str("    output logic [63:0] result,\n");
    sv.push_str("    output logic        valid\n");
    sv.push_str(");\n\n");

    for (index, spec) in program.constraints.iter().enumerate() {
        sv.push_str(&format!("    // {}\n", describe_spec(spec)));
        sv.push_str(&format!("    wire c{index};\n"));
        sv.push_str(&instance(index, spec));
        sv.push('\n');
    }

    match program.constraints.len() {
        0 => sv.push_str("    // No constraints: the whole space is admissible.\n    wire constraint_result = 1'b1;\n"),
        1 => sv.push_str("    // One constraint needs no gate.\n    wire constraint_result = c0;\n"),
        n => {
            let terms = (0..n)
                .map(|i| format!("c{i}"))
                .collect::<Vec<_>>()
                .join(&format!(" {} ", program.compose.operator()));
            sv.push_str(&format!(
                "    // The declared join, {}.\n    wire constraint_result = {terms};\n",
                program.compose.word()
            ));
        }
    }

    sv.push_str("\n    wire [63:0] projection;\n\n");
    sv.push_str(&format!("    {} u_projector (\n", projector.module_name()));
    sv.push_str("        .coord(coord),\n");
    sv.push_str("        .result(projection)\n");
    sv.push_str("    );\n\n");

    sv.push_str("    observe u_observe (\n");
    sv.push_str("        .constraint_result(constraint_result),\n");
    sv.push_str("        .projection(projection),\n");
    sv.push_str("        .result(result),\n");
    sv.push_str("        .valid(valid)\n");
    sv.push_str("    );\n\n");

    sv.push_str("endmodule\n");
    sv
}

fn describe_spec(spec: &ConstraintSpec) -> String {
    match spec {
        ConstraintSpec::Even => "even".to_string(),
        ConstraintSpec::Range { min, max } => format!("range [{min}, {max}]"),
        ConstraintSpec::Eq { value } => format!("eq {value}"),
        ConstraintSpec::Gt { value } => format!("gt {value}"),
    }
}

fn instance(index: usize, spec: &ConstraintSpec) -> String {
    let (unit, ports) = match spec {
        ConstraintSpec::Even => ("ck_even", String::new()),
        ConstraintSpec::Range { min, max } => (
            "ck_range",
            format!(
                "        .min_val({}),\n        .max_val({}),\n",
                word(*min),
                word(*max)
            ),
        ),
        ConstraintSpec::Eq { value } => ("ck_eq", format!("        .target({}),\n", word(*value))),
        ConstraintSpec::Gt { value } => {
            ("ck_gt", format!("        .threshold({}),\n", word(*value)))
        }
    };

    format!(
        "    {unit} u_c{index} (\n        .coord(coord),\n{ports}        .result(c{index})\n    );\n"
    )
}

/// A bound as a 64-bit pattern. Hex is exact for every i64, including the minimum, and the unit reads the pattern
/// as signed, so the literal carries the value without the emitter having to restate the order.
fn word(value: i64) -> String {
    format!("64'h{:016x}", value as u64)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn narrow() -> ConstraintProgram {
        ConstraintProgram {
            constraints: vec![
                ConstraintSpec::Even,
                ConstraintSpec::Range { min: 0, max: 10 },
            ],
            compose: ComposeOp::And,
        }
    }

    #[test]
    fn bounds_are_baked_in_their_two_complement_form() {
        let sv = emit_observation_sv(
            "m",
            &ConstraintProgram {
                constraints: vec![ConstraintSpec::Range { min: -2, max: 10 }],
                compose: ComposeOp::And,
            },
            ProjectorUnit::Identity,
        );
        assert!(sv.contains(".min_val(64'hfffffffffffffffe)"), "{sv}");
        assert!(sv.contains(".max_val(64'h000000000000000a)"), "{sv}");
    }

    #[test]
    fn kinds_instantiate_the_units_that_carry_them() {
        let sv = emit_observation_sv("m", &narrow(), ProjectorUnit::Identity);
        assert!(sv.contains("    ck_even u_c0 ("), "{sv}");
        assert!(sv.contains("    ck_range u_c1 ("), "{sv}");
        assert!(sv.contains(".min_val(64'h0000000000000000)"), "{sv}");
        assert!(sv.contains(".max_val(64'h000000000000000a)"), "{sv}");
    }

    #[test]
    fn the_declared_join_is_the_gate_that_is_emitted() {
        let and = emit_observation_sv("m", &narrow(), ProjectorUnit::Identity);
        assert!(and.contains("wire constraint_result = c0 && c1;"), "{and}");

        let or = emit_observation_sv(
            "m",
            &ConstraintProgram {
                compose: ComposeOp::Or,
                ..narrow()
            },
            ProjectorUnit::Identity,
        );
        assert!(or.contains("wire constraint_result = c0 || c1;"), "{or}");
    }

    #[test]
    fn an_empty_program_admits_the_whole_space() {
        let sv = emit_observation_sv(
            "m",
            &ConstraintProgram {
                constraints: Vec::new(),
                compose: ComposeOp::And,
            },
            ProjectorUnit::Identity,
        );
        assert!(sv.contains("wire constraint_result = 1'b1;"), "{sv}");
        assert!(!sv.contains("u_c0"), "{sv}");
    }

    #[test]
    fn the_projection_and_the_reject_rule_are_the_units_not_copies() {
        let sv = emit_observation_sv("m", &narrow(), ProjectorUnit::Parity);
        assert!(sv.contains("    proj_parity u_projector ("), "{sv}");
        assert!(sv.contains("    observe u_observe ("), "{sv}");
        assert!(sv.contains(".projection(projection)"), "{sv}");
        assert!(sv.contains(".valid(valid)"), "{sv}");
        // The sentinel belongs to observe. An emitter that wrote it would be a second definition of the reject rule.
        assert!(!sv.contains("8000000000000000"), "{sv}");
    }
}
