// ============================================================================
// Pure-Rust fallback — logic identical to RISC-V asm. Tested on CI.
// ============================================================================

#[cfg(not(target_arch = "riscv64"))]
pub mod fallback {
    // ── Observe: constraints ──
    pub fn ck_even(v: i64) -> u32 {
        ((v & 1) ^ 1) as u32
    }
    pub fn ck_range_0_10(v: i64) -> u32 {
        (v >= 0 && v <= 10) as u32
    }
    pub fn ck_range(v: i64, lo: i64, hi: i64) -> u32 {
        (v >= lo && v <= hi) as u32
    }
    pub fn ck_eq_val(v: i64, t: i64) -> u32 {
        (v == t) as u32
    }
    pub fn ck_gt(v: i64, t: i64) -> u32 {
        (v > t) as u32
    }
    pub fn compose_and(fa: fn(i64) -> u32, fb: fn(i64) -> u32, v: i64) -> u32 {
        fa(v) & fb(v)
    }
    pub fn compose_or(fa: fn(i64) -> u32, fb: fn(i64) -> u32, v: i64) -> u32 {
        fa(v) | fb(v)
    }
    pub fn proj_id(v: i64) -> i64 {
        v
    }
    pub fn proj_sum2d(a: i64, b: i64) -> i64 {
        a + b
    }
    pub fn proj_sum3d(a: i64, b: i64, c: i64) -> i64 {
        a + b + c
    }
    pub fn proj_parity(v: i64) -> i64 {
        v & 1
    }
    pub fn proj_negate(v: i64) -> i64 {
        -v
    }
    pub fn observe(field: fn(i64) -> u32, coord: i64, proj: fn(i64) -> i64) -> i64 {
        if field(coord) != 0 {
            proj(coord)
        } else {
            i64::MIN
        }
    }

    // ── Collapse ──
    pub fn collapse_sum(coords: &[i64]) -> i64 {
        coords.iter().sum()
    }
    pub fn collapse_min(coords: &[i64]) -> i64 {
        coords.iter().copied().min().unwrap_or(i64::MAX)
    }
    pub fn collapse_max(coords: &[i64]) -> i64 {
        coords.iter().copied().max().unwrap_or(i64::MIN)
    }
    pub fn collapse_product(coords: &[i64]) -> i64 {
        coords.iter().product()
    }
    pub fn collapse_count(results: &[i64], sentinel: i64) -> usize {
        results.iter().filter(|&&v| v != sentinel).count()
    }
    pub fn collapse_weighted_sum(coords: &[i64], weights: &[i64]) -> i64 {
        coords.iter().zip(weights.iter()).map(|(c, w)| c * w).sum()
    }
    pub fn collapse_weighted_avg(coords: &[i64], weights: &[i64]) -> i64 {
        let ws: i64 = weights.iter().sum();
        if ws == 0 {
            return 0;
        }
        collapse_weighted_sum(coords, weights) / ws
    }

    // ── Field ──
    pub fn field_add_constraint(
        field: &mut [u8; 512],
        constraint_fn: usize,
        constraint_id: u32,
    ) -> i32 {
        let num = u32::from_le_bytes(field[480..484].try_into().unwrap());
        if num >= 8 {
            return -1;
        }
        let idx = num as usize;
        field[idx * 8..idx * 8 + 8].copy_from_slice(&constraint_fn.to_le_bytes());
        field[64 + idx * 4..64 + idx * 4 + 4].copy_from_slice(&constraint_id.to_le_bytes());
        field[480..484].copy_from_slice(&(num + 1).to_le_bytes());
        0
    }
    pub fn field_remove_constraint(field: &mut [u8; 512], constraint_id: u32) -> i32 {
        let num = u32::from_le_bytes(field[480..484].try_into().unwrap()) as usize;
        for i in 0..num {
            let id = u32::from_le_bytes(field[64 + i * 4..64 + i * 4 + 4].try_into().unwrap());
            if id == constraint_id {
                for j in i..num - 1 {
                    let src_fn =
                        usize::from_le_bytes(field[(j + 1) * 8..(j + 2) * 8].try_into().unwrap());
                    field[j * 8..j * 8 + 8].copy_from_slice(&src_fn.to_le_bytes());
                    let src_id = u32::from_le_bytes(
                        field[64 + (j + 1) * 4..64 + (j + 2) * 4]
                            .try_into()
                            .unwrap(),
                    );
                    field[64 + j * 4..64 + j * 4 + 4].copy_from_slice(&src_id.to_le_bytes());
                }
                field[480..484].copy_from_slice(&((num as u32) - 1).to_le_bytes());
                return 0;
            }
        }
        0
    }
    pub fn field_clear(field: &mut [u8; 512]) {
        field[480..488].copy_from_slice(&[0u8; 8]);
    }
    pub fn field_add_transition(
        field: &mut [u8; 512],
        from_id: i64,
        to_id: i64,
        weight: i64,
    ) -> i32 {
        let num = u32::from_le_bytes(field[484..488].try_into().unwrap());
        if num >= 16 {
            return -1;
        }
        let idx = num as usize;
        let base = 96 + idx * 24;
        field[base..base + 8].copy_from_slice(&from_id.to_le_bytes());
        field[base + 8..base + 16].copy_from_slice(&to_id.to_le_bytes());
        field[base + 16..base + 24].copy_from_slice(&weight.to_le_bytes());
        field[484..488].copy_from_slice(&(num + 1).to_le_bytes());
        0
    }
    pub fn field_update_weight(
        field: &mut [u8; 512],
        from_id: i64,
        to_id: i64,
        new_weight: i64,
    ) -> i32 {
        let num = u32::from_le_bytes(field[484..488].try_into().unwrap()) as usize;
        for i in 0..num {
            let base = 96 + i * 24;
            let fid = i64::from_le_bytes(field[base..base + 8].try_into().unwrap());
            let tid = i64::from_le_bytes(field[base + 8..base + 16].try_into().unwrap());
            if fid == from_id && tid == to_id {
                field[base + 16..base + 24].copy_from_slice(&new_weight.to_le_bytes());
                return 0;
            }
        }
        -1
    }
    pub fn field_get_transitions(field: &[u8; 512], from_id: i64) -> Vec<(i64, i64)> {
        let num = u32::from_le_bytes(field[484..488].try_into().unwrap()) as usize;
        let mut out = Vec::new();
        for i in 0..num {
            let base = 96 + i * 24;
            let fid = i64::from_le_bytes(field[base..base + 8].try_into().unwrap());
            if fid == from_id {
                let tid = i64::from_le_bytes(field[base + 8..base + 16].try_into().unwrap());
                let w = i64::from_le_bytes(field[base + 16..base + 24].try_into().unwrap());
                out.push((tid, w));
            }
        }
        out
    }

    // ── Layout ──    // ── Layout ──
    pub fn layout_linear_1d(coord: i64, stride: i64) -> i64 {
        coord * stride
    }
    pub fn layout_linear_nd(coords: &[i64], strides: &[i64]) -> i64 {
        coords.iter().zip(strides.iter()).map(|(c, s)| c * s).sum()
    }
    pub fn layout_row_major_2d(x: i64, y: i64, width: i64, elem_size: i64) -> i64 {
        (y * width + x) * elem_size
    }
    pub fn layout_col_major_2d(x: i64, y: i64, height: i64, elem_size: i64) -> i64 {
        (x * height + y) * elem_size
    }
    pub fn morton_encode_2d(x: u32, y: u32) -> u64 {
        fn spread(v: u32) -> u64 {
            let mut x = v as u64;
            x = (x | (x << 16)) & 0x0000FFFF0000FFFF;
            x = (x | (x << 8)) & 0x00FF00FF00FF00FF;
            x = (x | (x << 4)) & 0x0F0F0F0F0F0F0F0F;
            x = (x | (x << 2)) & 0x3333333333333333;
            x = (x | (x << 1)) & 0x5555555555555555;
            x
        }
        spread(x) | (spread(y) << 1)
    }

    // ── Adjacency ──
    pub fn adj_grid_4(
        x: i64,
        y: i64,
        min_x: i64,
        max_x: i64,
        min_y: i64,
        max_y: i64,
    ) -> Vec<(i64, i64)> {
        let mut r = Vec::with_capacity(4);
        if x + 1 <= max_x {
            r.push((x + 1, y));
        }
        if x - 1 >= min_x {
            r.push((x - 1, y));
        }
        if y + 1 <= max_y {
            r.push((x, y + 1));
        }
        if y - 1 >= min_y {
            r.push((x, y - 1));
        }
        r
    }
    pub fn adj_manhattan_1d(coord: i64, distance: u32, min_coord: i64, max_coord: i64) -> Vec<i64> {
        let mut r = Vec::new();
        for d in 1..=distance as i64 {
            let p = coord + d;
            if p <= max_coord {
                r.push(p);
            }
            let n = coord - d;
            if n >= min_coord {
                r.push(n);
            }
        }
        r
    }
    pub fn adj_graph_edges(edges: &[(i64, i64)], from_id: i64) -> Vec<i64> {
        edges
            .iter()
            .filter(|&&(f, _)| f == from_id)
            .map(|&(_, t)| t)
            .collect()
    }
}

