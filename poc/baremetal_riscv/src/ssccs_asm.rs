//! SSCCS core concepts in RISC-V assembly — with pure-Rust software fallback.
//!
//! Each concept has its own `.S` file under `asm/`:
//! - `observe_full.S`   — Observation pipeline (constraints, composition, projectors)
//! - `collapse.S`       — Multi-segment reduction (sum, min, max, product, weighted)
//! - `field_update.S`   — Field mutation (constraint add/remove, transition update)
//! - `scheme_layout.S`  — Coordinate-to-address mapping (linear, row-major, z-order)
//! - `scheme_adjacency.S` — Structural neighbor discovery (grid, manhattan, graph)
//!
//! The `asm_data` module (generated by `build.rs`) exposes `.8byte` constants
//! from each file as a submodule (e.g. `asm_data::observe_full::SEG_0`).
//!
//! Validation strategy:
//!   RISC-V target: actual assembly via `global_asm!`
//!   Other targets:  pure-Rust fallback with identical logic
//!   Golden anchor:  test reads GOLDEN_* from `.S` files and verifies correctness
//!
//! This ensures changing a `.S` file forces updating its golden anchors,
//! which forces updating the Rust tests — keeping both in sync.

#![allow(dead_code)]

